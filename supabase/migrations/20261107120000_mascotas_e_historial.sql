-- Mascotas de cada usuario, historial veterinario y fotos.
-- Antes vivían en el localStorage de cada navegador; ahora quedan ligadas a la cuenta.
--
-- Se EXTIENDE la tabla Mascota del modelo ER (ID_Mascota, M_nombre, M_edad, M_peso) con
-- columnas nuevas; no se borra ni cambia ninguna columna existente. Las filas que se
-- inserten a mano desde el SQL Editor (sin user_id) siguen funcionando para el ramo,
-- pero no aparecen en la web, porque la web solo muestra las mascotas de cada usuario.

-- ---------- Mascota: columnas nuevas ----------

alter table public.mascota
  add column if not exists user_id uuid default auth.uid() references auth.users (id) on delete cascade;
alter table public.mascota add column if not exists especie text;
alter table public.mascota add column if not exists raza text;
alter table public.mascota add column if not exists foto_path text;
alter table public.mascota add column if not exists creado_en timestamptz not null default now();

-- ID_Mascota pasa a generarse solo (antes había que escribirlo a mano en cada INSERT).
-- Los ids que ya existan o se escriban manualmente siguen siendo válidos.
do $$
begin
  if pg_get_serial_sequence('public.mascota', 'id_mascota') is null
     and exists (
       select 1 from pg_attribute
       where attrelid = 'public.mascota'::regclass and attname = 'id_mascota'
         and attidentity = '' and attgenerated = ''
     ) then
    alter table public.mascota alter column id_mascota add generated by default as identity;
    perform setval(
      pg_get_serial_sequence('public.mascota', 'id_mascota'),
      (select coalesce(max(id_mascota), 0) + 1 from public.mascota),
      false
    );
  end if;
end $$;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'mascota_nombre_no_vacio' and conrelid = 'public.mascota'::regclass) then
    alter table public.mascota add constraint mascota_nombre_no_vacio check (char_length(btrim(m_nombre)) >= 1);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'mascota_especie_valida' and conrelid = 'public.mascota'::regclass) then
    alter table public.mascota add constraint mascota_especie_valida
      check (especie is null or especie in ('Perro', 'Gato', 'Ave', 'Conejo', 'Animal exótico', 'Otro'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'mascota_raza_largo' and conrelid = 'public.mascota'::regclass) then
    alter table public.mascota add constraint mascota_raza_largo check (raza is null or char_length(raza) <= 80);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'mascota_edad_rango' and conrelid = 'public.mascota'::regclass) then
    alter table public.mascota add constraint mascota_edad_rango check (m_edad is null or (m_edad >= 0 and m_edad <= 100));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'mascota_peso_rango' and conrelid = 'public.mascota'::regclass) then
    alter table public.mascota add constraint mascota_peso_rango check (m_peso is null or (m_peso > 0 and m_peso <= 1000));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'mascota_foto_propia' and conrelid = 'public.mascota'::regclass) then
    alter table public.mascota add constraint mascota_foto_propia
      check (foto_path is null or (user_id is not null and foto_path like user_id::text || '/%'));
  end if;
end $$;

create index if not exists mascota_user_id_idx on public.mascota (user_id);

-- ---------- historial veterinario (controles y vacunas anotados por el dueño) ----------

create table if not exists public.historial_mascota (
  id uuid primary key default gen_random_uuid(),
  mascota_id integer not null references public.mascota (id_mascota) on delete cascade,
  tipo text not null check (tipo in ('controles', 'vacunas')),
  descripcion text not null check (char_length(btrim(descripcion)) between 1 and 100),
  fecha date not null,
  estado text not null,
  creado_en timestamptz not null default now(),
  check (
    (tipo = 'controles' and estado in ('Programado', 'Realizado'))
    or (tipo = 'vacunas' and estado in ('Pendiente', 'Aplicada'))
  )
);

create index if not exists historial_mascota_mascota_idx
  on public.historial_mascota (mascota_id, fecha desc);

-- ---------- permisos ----------

revoke all on public.mascota, public.historial_mascota from anon;
grant select, insert, update, delete on public.mascota, public.historial_mascota to authenticated;
grant all on public.mascota, public.historial_mascota to service_role;

-- ---------- row level security ----------

alter table public.mascota enable row level security;
alter table public.historial_mascota enable row level security;

do $$
declare
  r record;
begin
  for r in
    select tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('mascota', 'historial_mascota')
  loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

create policy mascota_select on public.mascota
  for select to authenticated using (user_id = (select auth.uid()));
create policy mascota_insert on public.mascota
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy mascota_update on public.mascota
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
create policy mascota_delete on public.mascota
  for delete to authenticated using (user_id = (select auth.uid()));

create policy historial_select on public.historial_mascota
  for select to authenticated using (
    exists (
      select 1 from public.mascota m
      where m.id_mascota = historial_mascota.mascota_id and m.user_id = (select auth.uid())
    )
  );
create policy historial_insert on public.historial_mascota
  for insert to authenticated with check (
    exists (
      select 1 from public.mascota m
      where m.id_mascota = historial_mascota.mascota_id and m.user_id = (select auth.uid())
    )
  );
create policy historial_update on public.historial_mascota
  for update to authenticated
  using (
    exists (
      select 1 from public.mascota m
      where m.id_mascota = historial_mascota.mascota_id and m.user_id = (select auth.uid())
    )
  )
  with check (
    exists (
      select 1 from public.mascota m
      where m.id_mascota = historial_mascota.mascota_id and m.user_id = (select auth.uid())
    )
  );
create policy historial_delete on public.historial_mascota
  for delete to authenticated using (
    exists (
      select 1 from public.mascota m
      where m.id_mascota = historial_mascota.mascota_id and m.user_id = (select auth.uid())
    )
  );

-- ---------- fotos (Storage) ----------
-- Bucket privado: las fotos se muestran con URLs firmadas temporales.
-- Ruta de cada archivo: <user_id>/<nombre-aleatorio>.jpg

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'fotos-mascotas', 'fotos-mascotas', false, 5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists fotos_mascotas_select on storage.objects;
drop policy if exists fotos_mascotas_insert on storage.objects;
drop policy if exists fotos_mascotas_update on storage.objects;
drop policy if exists fotos_mascotas_delete on storage.objects;

create policy fotos_mascotas_select on storage.objects
  for select to authenticated using (
    bucket_id = 'fotos-mascotas' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy fotos_mascotas_insert on storage.objects
  for insert to authenticated with check (
    bucket_id = 'fotos-mascotas' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy fotos_mascotas_update on storage.objects
  for update to authenticated
  using (bucket_id = 'fotos-mascotas' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (bucket_id = 'fotos-mascotas' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy fotos_mascotas_delete on storage.objects
  for delete to authenticated using (
    bucket_id = 'fotos-mascotas' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
